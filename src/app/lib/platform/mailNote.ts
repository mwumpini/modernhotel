function escapeHtml(value: string) {
  return value.replace(/[&<>"]/g, (ch) => (
    ch === '&' ? '&amp;' : ch === '<' ? '&lt;' : ch === '>' ? '&gt;' : '&quot;'
  ));
}

/** Short inbox note. The document itself is the PDF. */
export function mailNote(input: { name: string; documentName: string; facility: string }) {
  const name = escapeHtml(input.name || 'Guest');
  const documentName = escapeHtml(input.documentName);
  const facility = escapeHtml(input.facility || 'the facility');
  return `<div style="font-family:Arial,sans-serif;font-size:15px;color:#111827;line-height:1.5">
    <p>Dear ${name},</p>
    <p>Please find your ${documentName} attached.</p>
    <p style="margin-top:24px">Yours sincerely,</p>
    <p style="margin:0;font-weight:700">${facility}</p>
    <p style="margin-top:20px;font-size:12px;color:#6b7280">This message was generated by the system. It was not typed by a member of staff.</p>
    <p style="font-size:12px;color:#6b7280"><strong>Security and data protection.</strong> This note and the attached PDF are meant only for ${name}. If you are not that person, delete this message and do not open the file. The attachment can hold personal and billing details, so do not forward it. Do not reply with a password, a card number, or a copy of an identity card. ${facility} will not ask for those by email.</p>
  </div>`;
}
